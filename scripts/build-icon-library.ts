const names = Object.keys(WANTED);
const missing = names.filter((name) => !nodes[name]);
if (missing.length) console.warn(`not in lucide-static (${missing.length}), left out: ${missing.join(", ")}`);

const esc = (value: string) => value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const body = (list: IconNode[]) =>
	list
		.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== "key").map(([key, value]) => `${key}="${esc(String(value))}"`).join(" ")}/>`)
		.join("");

const icons = names.filter((name) => nodes[name]).map((name) => ({ name, keywords: WANTED[name], body: body(nodes[name]) }));
const out = `// GENERATED by scripts/build-icon-library.ts from lucide-static (ISC licence). Do not edit by hand.
export type LibraryIcon = { name: string; keywords: string; body: string };

/** The inner markup of each icon: draw it inside a 24 x 24 <svg> with stroke="currentColor" (see icons/render.ts). */
export const ICON_LIBRARY: LibraryIcon[] = [
${icons.map((icon) => `\t${JSON.stringify(icon)},`).join("\n")}
];
`;
writeFileSync(join(root, "src/admin/icons/library.ts"), out);
console.log(`${icons.length} icons, ${(out.length / 1024).toFixed(1)} KB`);
